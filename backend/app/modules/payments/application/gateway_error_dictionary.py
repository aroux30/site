def translate_gateway_error(provider: str, error_code: int | str | None) -> str:
    """Translate raw PSP gateway error code into a friendly Persian explanation."""
    if error_code is None:
        return "خطای نامشخص در ارتباط با درگاه پرداخت بانکی رخ داده است."

    provider_clean = (provider or "").strip().lower()

    try:
        code_int = int(str(error_code).strip())
    except ValueError:
        return f"خطای درگاه: {error_code}"

    if "zarinpal" in provider_clean:
        return ZARINPAL_ERRORS.get(code_int, f"خطای زرین‌پال با کد {code_int}")
    if "mellat" in provider_clean:
        return MELLAT_ERRORS.get(code_int, f"خطای بانک ملت با کد {code_int}")
    if "saman" in provider_clean:
        return SAMAN_ERRORS.get(code_int, f"خطای بانک سامان با کد {code_int}")
    if "zibal" in provider_clean:
        return ZIBAL_ERRORS.get(code_int, f"خطای زیبال با کد {code_int}")

    return f"پاسخ درگاه بانکی: کد {code_int}"
