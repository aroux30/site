import fs from "node:fs";
import path from "node:path";

const PROJECT_ROOT = path.resolve("C:/Users/Administrator/Desktop/site");
const REGRESSIONS_DIR = path.join(PROJECT_ROOT, ".loop", "audits", "regressions");
const REPORT_PATH = path.join(PROJECT_ROOT, ".loop", "audits", "deterministic-report.json");

export function promoteRegressions() {
  console.log(">>> [Promote-Regression] Checking for solved defects to promote into permanent regression tests...");
  fs.mkdirSync(REGRESSIONS_DIR, { recursive: true });

  if (!fs.existsSync(REPORT_PATH)) {
    console.log("    No deterministic-report.json found. Skipping promotion.");
    return;
  }

  const report = JSON.parse(fs.readFileSync(REPORT_PATH, "utf8"));
  if (!report.passed) {
    console.log("    Report did not pass; cannot promote unverified changes.");
    return;
  }

  // Create or update baseline regression test suite
  const regressionFile = path.join(REGRESSIONS_DIR, "builder-regression-suite.spec.ts");
  const testContent = `// Auto-promoted regression tests generated by self-healing loop
import { test, expect } from "@playwright/test";

test.describe("Builder Regression Invariants", () => {
  test("LayersTree action buttons must never have opacity-0 and remain permanently visible", async ({ page }) => {
    await page.goto("http://localhost:3000/e2e-isolated-scratchpad?visual_editor=true");
    await page.mouse.move(0, 0);

    const layersTab = page.getByRole("button", { name: "لایه‌ها" });
    if (await layersTab.isVisible()) {
      await layersTab.click();
    }

    const rows = page.locator("[data-layer-row]");
    const count = await rows.count();
    expect(count).toBeGreaterThan(0);

    for (let i = 0; i < count; i++) {
      const row = rows.nth(i);
      const buttons = row.locator("button");
      const btnCount = await buttons.count();
      for (let b = 0; b < btnCount; b++) {
        const btn = buttons.nth(b);
        const cls = (await btn.getAttribute("class")) || "";
        expect(cls).not.toContain("opacity-0");
        expect(cls).not.toContain("invisible");
        expect(cls).not.toContain("hidden");
      }
    }
  });

  test("Empty container guide button must be visible with height >= 80px", async ({ page }) => {
    await page.goto("http://localhost:3000/e2e-isolated-scratchpad?visual_editor=true");
    const frame = page.frameLocator('iframe[title="Visual Builder Canvas"]');
    const guide = frame.locator("text=+ افزودن بلوک به این بخش").first();
    await expect(guide).toBeVisible();
  });
});
`;

  fs.writeFileSync(regressionFile, testContent, "utf8");
  console.log(`>>> Promoted permanent regression test to: ${regressionFile}`);
}

if (process.argv[1] && process.argv[1].endsWith("promote-regression.mjs")) {
  promoteRegressions();
}
